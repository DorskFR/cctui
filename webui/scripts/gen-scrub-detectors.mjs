#!/usr/bin/env node
// Emits src/lib/scrubDetectors.generated.ts from the Rust BUILTINS table, so
// the settings UI cannot drift from the engine. Run via `npm run bindings`.
// `crates/cctui-crypto/src/redact.rs::builtin_list_matches_the_webui_copy`
// fails the build if this file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const webui = dirname(dirname(fileURLToPath(import.meta.url)));
const rust = readFileSync(join(webui, "../crates/cctui-crypto/src/redact.rs"), "utf8");

const entries = [];
const re = /category:\s*"([a-z0-9_]+)",\s*\n\s*family:\s*"([a-z]+)"/g;
for (const m of rust.matchAll(re)) entries.push({ category: m[1], family: m[2] });
if (entries.length === 0) throw new Error("no detectors parsed from redact.rs");

const body = entries
  .map((e) => `\t{ category: '${e.category}', family: '${e.family}' }`)
  .join(",\n");

writeFileSync(
  join(webui, "src/lib/scrubDetectors.generated.ts"),
  `// Generated by webui/scripts/gen-scrub-detectors.mjs. Do not edit.\n` +
    `// Source of truth: crates/cctui-crypto/src/redact.rs (BUILTINS).\n\n` +
    `export type ScrubFamily = 'forge' | 'ai' | 'cloud' | 'registry' | 'saas' | 'generic';\n\n` +
    `export interface ScrubDetector {\n\tcategory: string;\n\tfamily: ScrubFamily;\n}\n\n` +
    `export const BUILTIN_SCRUB_DETECTORS: ScrubDetector[] = [\n${body}\n];\n`,
);
console.log(`wrote ${entries.length} detectors`);
